// SecondRevision - the dust in the air (Wind, docs/terv-novenyzet-szel.md 5.3): a vertex shader that makes motes of
// dust round the eye, put in front of the world's own see-through pixel shader (FSolidPass::MakeDust). A mote is an
// instance: one to a cell of a grid round the eye that stands in the world - a cell's mote is the same whatever the
// frame - drifting with the wind through its cell and fading in and out at the cell's sides. It has no light of its
// own: it is seen where a lamp lights the air round it, by the lamps the block lists, and nowhere else. Under a roof
// (each column's, GRoof) it fades out, and all of it as the eye goes indoors (GLampCount.y).
//
// Plain ASCII, as the C string it is.
#pragma once

static const char* GDustShader =
"cbuffer Frame : register(b0)\n"
"{\n"
"    float2 InvHalfSize;\n"
"    float2 Jitter;\n"
"    float  LightBoost;\n"
"    float  MipBias;\n"
"};\n"
"cbuffer Dust : register(b2)\n"
"{\n"
"    float4 GView[3];      // world to view: each row an axis (xyz) and that axis's offset (w)\n"
"    float4 GScreen;       // the engine's screen centre (x, y), its projection (z), the level's time (w)\n"
"    float4 GEye;          // the eye in the world (xyz), a cell's side (w)\n"
"    float4 GGrid;         // the grid's cells across (x), along (y), up (z); how bright a lit mote is (w)\n"
"    float4 GWind;         // the wind's way (x, y); how far the motes have drifted along it, units (z); a mote's\n"
"                          // size (w)\n"
"    float4 GLampCount;    // how many lamps (x); the dust's own fade, out as the eye goes indoors and back (y); the\n"
"                          // least and the most half-width of a mote on the screen, pixels (z, w)\n"
"    float4 GLamps[512];   // a lamp: its place (xyz) and reach (w), then its colour (rgb) - RenderDevice's DustLampRoom\n"
"    float4 GRoof[1024];   // each column of the grid, x first, four a row: the height its roof is at - -1e9 open sky,\n"
"                          // 1e9 shut - RenderDevice's DustCellsAcross squared\n"
"    float4 GGust;         // the gusts, as the grass has them (RdxMath::WindAt): a full one's push, units a second\n"
"                          // (x); a gust's length (y) and how fast its front travels (z)\n"
"};\n"
"struct VSOut { float4 Pos : SV_Position; float2 Uv : TEXCOORD0; float2 Lv : TEXCOORD1;\n"
"               float4 Colour : COLOR; float4 Pom : TEXCOORD2; float3 View : TEXCOORD3; };\n"
"\n"
"uint Hash(uint X)\n"
"{\n"
"    X ^= X >> 16; X *= 0x7feb352du; X ^= X >> 15; X *= 0x846ca68bu; X ^= X >> 16;\n"
"    return X;\n"
"}\n"
"float Rand(inout uint S)\n"
"{\n"
"    S = Hash(S);\n"
"    return float(S & 0xFFFFFFu) / 16777216.0f;\n"
"}\n"
"VSOut Nothing()\n"
"{\n"
"    VSOut O = (VSOut)0;\n"
"    O.Pos = float4(0.0f, 0.0f, -1.0f, 1.0f);\n"
"    return O;\n"
"}\n"
"\n"
"// How open the air is at a height over a column of the grid: none under the column's roof, all of it from 24 units\n"
"// above it - an open column's roof lies below everything.\n"
"float Open(int2 C, float Z)\n"
"{\n"
"    C = clamp(C, int2(0, 0), int2((int)GGrid.x - 1, (int)GGrid.y - 1));\n"
"    const uint  I    = (uint)C.x + (uint)C.y * (uint)GGrid.x;\n"
"    const float Roof = GRoof[I >> 2u][I & 3u];\n"
"    return saturate((Z - Roof) / 24.0f);\n"
"}\n"
"\n"
"// A wave of a gust's push, A sin F or A cos F, its phase F going round Om turns a second the other way, added up\n"
"// over time: a quarter turned, over two pi Om. None for a wave that hardly goes round.\n"
"float SurgeSin(float A, float F, float Om)\n"
"{\n"
"    return (abs(Om) > 1e-3f) ? A * cos(F) / (6.2831853f * Om) : 0.0f;\n"
"}\n"
"float SurgeCos(float A, float F, float Om)\n"
"{\n"
"    return (abs(Om) > 1e-3f) ? -A * sin(F) / (6.2831853f * Om) : 0.0f;\n"
"}\n"
"\n"
"VSOut VSDust(uint Vertex : SV_VertexID, uint Instance : SV_InstanceID)\n"
"{\n"
"    const uint Nx = (uint)GGrid.x, Ny = (uint)GGrid.y, Nz = (uint)GGrid.z;\n"
"    const uint Iz = Instance / (Nx * Ny);\n"
"    if (Iz >= Nz)\n"
"        return Nothing();\n"
"    const int3  In   = int3(Instance % Nx, (Instance / Nx) % Ny, Iz);\n"
"    const float Side = GEye.w;\n"
"    const int3  Cell = int3(floor(GEye.xyz / Side)) - int3(Nx, Ny, Nz) / 2 + In;\n"
"    uint S = Hash((uint)Cell.x * 73856093u ^ (uint)Cell.y * 19349663u ^ (uint)Cell.z * 83492791u);\n"
"    // Its place in the cell, drifting with the wind - downwind, a little across - and slowly up and down; out of one\n"
"    // side it comes in at the other, faded out and in again at the sides.\n"
"    const float  T     = GScreen.w;\n"
"    const float3 Seed  = float3(Rand(S), Rand(S), Rand(S));\n"
"    const float  Pace  = 0.6f + 0.8f * Rand(S);\n"
"    // The gusts' fronts going by - the grass's (RdxMath::WindAt), travelling downwind -, over the drift's mean:\n"
"    // what the fronts push the mote by as they pass the mote's cell, added up over their rise and their fall, so\n"
"    // the mote surges as a front reaches it and falls back after. The gust's share there,\n"
"    // G = (0.5 + 0.5 sin F1 (0.6 + 0.4 sin F2))^2 with F1 and F2 going round W1 and W2 turns a second, is 0.305\n"
"    // and these waves round it, each added up on its own (SurgeSin, SurgeCos).\n"
"    const float2 Mid    = (float2(Cell.xy) + 0.5f) * Side;\n"
"    const float  Along  = dot(Mid, GWind.xy);\n"
"    const float  Across = dot(Mid, float2(-GWind.y, GWind.x));\n"
"    const float  W1     = GGust.z / GGust.y;\n"
"    const float  W2     = W1 * 0.83f / 0.37f;\n"
"    const float  F1     = 6.2831853f * (Along / GGust.y - W1 * T);\n"
"    const float  F2     = 6.2831853f * (Along * 0.61f / (GGust.y * 0.37f) + Across / (GGust.y * 0.9f) + 0.27f -\n"
"                                        W2 * T);\n"
"    const float  Surge  = GGust.x * (SurgeSin(0.30f, F1, W1) + SurgeCos(0.10f, F1 - F2, W1 - W2) +\n"
"                                     SurgeCos(-0.10f, F1 + F2, W1 + W2) + SurgeSin(0.06f, F2, W2) +\n"
"                                     SurgeCos(-0.01f, 2.0f * F2, 2.0f * W2) +\n"
"                                     SurgeCos(-0.055f, 2.0f * F1, 2.0f * W1) +\n"
"                                     SurgeSin(-0.03f, F2 + 2.0f * F1, W2 + 2.0f * W1) +\n"
"                                     SurgeSin(-0.03f, F2 - 2.0f * F1, W2 - 2.0f * W1) +\n"
"                                     SurgeCos(0.005f, 2.0f * (F1 - F2), 2.0f * (W1 - W2)) +\n"
"                                     SurgeCos(0.005f, 2.0f * (F1 + F2), 2.0f * (W1 + W2)));\n"
"    const float2 Drift  = (GWind.xy + float2(-GWind.y, GWind.x) * (Rand(S) - 0.5f)) *\n"
"                          ((GWind.z + Surge) * Pace / Side);\n"
"    const float3 F     = frac(Seed + float3(Drift, 0.04f * sin(T * (0.2f + 0.3f * Seed.x) + 6.2831853f * Seed.y)));\n"
"    const float3 Edge  = min(F, 1.0f - F);\n"
"    float Fade = saturate(min(Edge.x, min(Edge.y, Edge.z)) * 10.0f);\n"
"    const float3 W = (float3(Cell) + F) * Side;\n"
"    // The lamps that light the air there.\n"
"    float3 L = float3(0.0f, 0.0f, 0.0f);\n"
"    const int Lamps = (int)GLampCount.x;\n"
"    [loop] for (int k = 0; k < Lamps; k++)\n"
"    {\n"
"        const float4 A = GLamps[2 * k];\n"
"        const float  D = length(W - A.xyz);\n"
"        if (D < A.w)\n"
"        {\n"
"            // Steeper than the lamp's own falloff: dust shows in the light near a lamp, not in its faint edge.\n"
"            const float R = 1.0f - D / A.w;\n"
"            L += GLamps[2 * k + 1].rgb * (R * R * R);\n"
"        }\n"
"    }\n"
"    // Fewer of them seen further off, and none at the grid's far reach.\n"
"    Fade *= saturate(1.0f - length(W - GEye.xyz) / (0.5f * min(Nx, Ny) * Side));\n"
"    // Under a roof none: the open air read between the four columns nearest the mote, so it fades as it drifts in.\n"
"    const float2 At = float2(In.xy) + F.xy - 0.5f;\n"
"    const int2   C0 = int2(floor(At));\n"
"    const float2 Fr = At - float2(C0);\n"
"    const float  Air = lerp(lerp(Open(C0, W.z), Open(C0 + int2(1, 0), W.z), Fr.x),\n"
"                            lerp(Open(C0 + int2(0, 1), W.z), Open(C0 + int2(1, 1), W.z), Fr.x), Fr.y);\n"
"    Fade *= Air * GLampCount.y;\n"
"    L *= Fade * GGrid.w * (0.5f + Rand(S));\n"
"    if (max(L.r, max(L.g, L.b)) < 0.003f)\n"
"        return Nothing();\n"
"    // A small square facing the eye, its corners off the place in view space.\n"
"    const float3 V = float3(dot(GView[0].xyz, W) + GView[0].w, dot(GView[1].xyz, W) + GView[1].w,\n"
"                            dot(GView[2].xyz, W) + GView[2].w);\n"
"    if (V.z < 1.0f)\n"
"        return Nothing();\n"
"    const float2 Corner = float2((Vertex & 1u) ? 1.0f : -1.0f, (Vertex & 2u) ? 1.0f : -1.0f);\n"
"    // Its half-width on the screen held between GLampCount.z and .w pixels; one drawn larger than it is, as much\n"
"    // fainter, so that a far one is a faint dot rather than nothing.\n"
"    const float  Half   = GWind.w * (0.6f + 0.8f * Rand(S));\n"
"    const float  Px     = Half * GScreen.z / V.z;\n"
"    const float  Drawn  = clamp(Px, GLampCount.z, GLampCount.w);\n"
"    L *= min(1.0f, (Px * Px) / (Drawn * Drawn));\n"
"    const float3 Vc     = V + float3(Corner * (Drawn * V.z / GScreen.z), 0.0f);\n"
"    VSOut O;\n"
"    O.Uv     = Corner * 0.5f + 0.5f;\n"
"    O.Lv     = float2(0.5f, 0.5f);\n"
"    O.Colour = float4(L, 1.0f);\n"
"    O.Pom    = 0.0f;\n"
"    O.Pos.x  = (GScreen.x * InvHalfSize.x - 1.0f + Jitter.x) * Vc.z + GScreen.z * InvHalfSize.x * Vc.x;\n"
"    O.Pos.y  = (1.0f - GScreen.y * InvHalfSize.y + Jitter.y) * Vc.z - GScreen.z * InvHalfSize.y * Vc.y;\n"
"    O.Pos.z  = 1.0f;\n"
"    O.Pos.w  = Vc.z;\n"
"    O.View   = Vc;\n"
"    return O;\n"
"}\n";
