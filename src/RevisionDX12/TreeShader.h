// SecondRevision - the trees and bushes grown by code (Trees3D, TreeGen.h): the vertex shader that stands a grown plant
// where the game's own stands, bends it in the wind and puts it on the screen - in front of the world's own pixel
// shader (FSolidPass::MakeTree), so the plant takes the bark's and the leaves' pictures, the stencil kind of an actor's
// mesh and with it the lamps' shadows, and the flashlight, as the game's tree did.
//
// The leaves have a vertex shader of their own, VSLeaf: each leaf one instance of the blade's frame (TreeGen.h's
// FLeafInstance and LeafCorner), its corner the vertex's number in the frame.
//
// What it is handed (FSolidPass::TreeBlock, filled by RenderDevice.cpp's trees): the world-to-view rows and the engine's
// projection, the level's clock and wind, and the plant: where it stands, how it is turned, how large it is, its light
// along the world's six ways as the game lights a model there, and whether the wind reaches it. The vertices are
// TreeGen.h's FVertex.
//
// VSTreeMotion and VSLeafMotion lay the same at this frame's time and at the frame before's (GLight.x), for the motion
// vectors' pass (PlantMotion.h).
//
// Plain ASCII, as the C string it is.
#pragma once

#include "PlantMotion.h"

static const char* GTreeShader =
RDX_PLANT_MOTION
"cbuffer Frame : register(b0)\n"
"{\n"
"    float2 InvHalfSize;\n"
"    float2 Jitter;\n"
"    float  LightBoost;\n"
"    float  MipBias;\n"
"};\n"
"cbuffer Tree : register(b2)\n"
"{\n"
"    float4 GView[3];      // world to view: each row an axis (xyz) and that axis's offset (w)\n"
"    float4 GScreen;       // the engine's screen centre (x, y), its projection (z), the level's time (w)\n"
"    float4 GWind;         // the wind: its direction (x, y), its base (z) and its gusts (w), 0 .. 1\n"
"    float4 GWindWave;     // a gust's length (x) and speed (y); the plant outdoors, 0..1 (z); its own beat (w)\n"
"    float4 GPlace;        // the plant's foot in the world (xyz); its turn about the upright, radians (w)\n"
"    float4 GSize;         // its scale across (x) and up (y); how far its bark picture's repeats go (z); its leaves'\n"
"                          // size for a far plant drawing only a share of them (w)\n"
"    float4 GLight;        // the frame before's time (x); the wind's strength, 0 .. 1 (y); the leaves' width, of\n"
"                          // their length - 0 for a leaf's half, 1 for an EZ-Tree card's whole (z); 1 for the leaves,\n"
"                          // 0 the bark (w)\n"
"    float4 GCube[6];      // its light along +x, -x, +y, -y, +z, -z (rgb): RdxMath::RtCubeLight's\n"
"};\n"
"struct VSIn  { float3 Pos : POSITION; float3 Normal : NORMAL; float2 Uv : TEXCOORD0; float4 WindA : TEXCOORD1;\n"
"               float4 WindB : TEXCOORD2; float4 Open : COLOR; };\n"
"struct VSOut { float4 Pos : SV_Position; float2 Uv : TEXCOORD0; float2 Lv : TEXCOORD1;\n"
"               float4 Colour : COLOR; float4 Pom : TEXCOORD2; float3 View : TEXCOORD3; };\n"
"\n"
"// RdxMath::WindAt, the same formula as the grass's: the gusts in 0 .. 1 of the full wind.\n"
"float2 WindAt(float2 P, float T)\n"
"{\n"
"    const float2 D      = GWind.xy;\n"
"    const float  Along  = dot(P, D);\n"
"    const float  Across = -P.x * D.y + P.y * D.x;\n"
"    const float  Wave   = max(GWindWave.x, 1.0f);\n"
"    const float  P1     = (Along - GWindWave.y * T) / Wave;\n"
"    const float  P2     = (Along * 0.61f - GWindWave.y * 0.83f * T) / (Wave * 0.37f) + Across / (Wave * 0.9f);\n"
"    float G = 0.5f + 0.5f * sin(6.2831853f * P1) * (0.6f + 0.4f * sin(6.2831853f * (P2 + 0.27f)));\n"
"    G = G * G;\n"
"    return D * (GWind.z + GWind.w * G);\n"
"}\n"
"\n"
"// How open the plant is round a point, each way (TreeGen.h's FOpenness): its average (x) and its lean (yzw, from 0 .. 1\n"
"// back to -1 .. 1, in the plant's own space - turned here as the plant is); towards a way D it is open by\n"
"// OpenGain * (average + lean . D), and takes OpenFloor + (1 - OpenFloor) of that of the light coming from there\n"
"// (TreeGen.h's OpenFloor and OpenGain).\n"
"static const float OpenFloor = 0.3f, OpenGain = 1.5f;\n"
"\n"
"// The light a face looking along N takes from the plant's cube: each way's by the square of N's part along it, and by\n"
"// how open the plant is that way where the face is - the crown shading itself.\n"
"float3 CubeLight(float3 N, float4 Open)\n"
"{\n"
"    const float  C    = cos(GPlace.w), S = sin(GPlace.w);\n"
"    const float3 L    = Open.yzw * 2.0f - 1.0f;\n"
"    const float3 Lean = float3(C * L.x - S * L.y, S * L.x + C * L.y, L.z);\n"
"    const float3 To   = OpenFloor + (1.0f - OpenFloor) * saturate(OpenGain * (Open.x + Lean));\n"
"    const float3 Back = OpenFloor + (1.0f - OpenFloor) * saturate(OpenGain * (Open.x - Lean));\n"
"    const float3 K    = N * N;\n"
"    return K.x * ((N.x >= 0.0f) ? GCube[0].rgb * To.x : GCube[1].rgb * Back.x) +\n"
"           K.y * ((N.y >= 0.0f) ? GCube[2].rgb * To.y : GCube[3].rgb * Back.y) +\n"
"           K.z * ((N.z >= 0.0f) ? GCube[4].rgb * To.z : GCube[5].rgb * Back.z);\n"
"}\n"
"\n"
"// A point of the plant's own space into the world at a time: scaled, turned about the upright, stood on its foot, and\n"
"// swayed by the wind outdoors - its chain's sways summed (TreeGen.h's FSway): its own branch's from that branch's foot,\n"
"// and each branch's it grows from at the point it grows from, down to the trunk's, each branch in its own beat, the\n"
"// whole plant's beat over them. A branch's foot keeps to the point it grows from; its tip swings the furthest.\n"
"// WindA, WindB: the sums - the bends (S0), and the bends by each beat's cosine and sine at the sway's three paces\n"
"// (C1 S1, C2 S2, C3 S3).\n"
"float3 Swayed(float3 Pos, float4 WindA, float4 WindB, float T)\n"
"{\n"
"    const float  C = cos(GPlace.w), S = sin(GPlace.w);\n"
"    const float3 L = float3(Pos.xy * GSize.x, Pos.z * GSize.y);\n"
"    float3 W = GPlace.xyz + float3(C * L.x - S * L.y, S * L.x + C * L.y, L.z);\n"
"    const float  Own    = 6.2831853f * GWindWave.w;\n"
"    const float  A1     = T * 1.7f + Own, A2 = T * 4.3f + 2.0f * Own, A3 = T * 2.3f + 3.0f * Own;\n"
"    const float  Sway   = WindA.x + 0.35f * (sin(A1) * WindA.y + cos(A1) * WindA.z) +\n"
"                          0.15f * (sin(A2) * WindA.w + cos(A2) * WindB.x);\n"
"    const float  Side   = 0.25f * (sin(A3) * WindB.y + cos(A3) * WindB.z);\n"
"    const float2 Push   = WindAt(GPlace.xy, T);\n"
"    const float2 Across = float2(-GWind.y, GWind.x) * Side;\n"
"    W.xy += (Push * Sway + Across * length(Push)) * (GSize.y * GWindWave.z);\n"
"    W.z  -= 0.15f * dot(Push, Push) * WindA.x * GSize.y * GWindWave.z;\n"
"    return W;\n"
"}\n"
"\n"
"// Into the view and onto the engine's screen.\n"
"void OnScreen(float3 W, inout VSOut O)\n"
"{\n"
"    const float3 V = float3(dot(GView[0].xyz, W) + GView[0].w, dot(GView[1].xyz, W) + GView[1].w,\n"
"                            dot(GView[2].xyz, W) + GView[2].w);\n"
"    O.Pos.x = (GScreen.x * InvHalfSize.x - 1.0f + Jitter.x) * V.z + GScreen.z * InvHalfSize.x * V.x;\n"
"    O.Pos.y = (1.0f - GScreen.y * InvHalfSize.y + Jitter.y) * V.z - GScreen.z * InvHalfSize.y * V.y;\n"
"    O.Pos.z = 1.0f;\n"
"    O.Pos.w = V.z;\n"
"    O.View  = V;\n"
"}\n"
"\n"
"VSOut VSTree(VSIn In)\n"
"{\n"
"    const float3 W = Swayed(In.Pos, In.WindA, In.WindB, GScreen.w);\n"
"    VSOut O;\n"
"    O.Uv = float2(In.Uv.x, In.Uv.y * GSize.z);\n"
"    O.Lv = float2(0.5f, 0.5f);\n"
"    // The light the game would give a face of a model there, by where it looks, each way's by how open the plant is\n"
"    // that way there (In.Open).\n"
"    const float  C = cos(GPlace.w), S = sin(GPlace.w);\n"
"    const float3 N = normalize(float3(C * In.Normal.x - S * In.Normal.y, S * In.Normal.x + C * In.Normal.y,\n"
"                                      In.Normal.z));\n"
"    O.Colour = float4(CubeLight(N, In.Open), 1.0f);\n"
"    O.Pom    = 0.0f;\n"
"    OnScreen(W, O);\n"
"    return O;\n"
"}\n"
"\n"
"// The motion vectors' pass: the bark now and the frame before.\n"
"MotionOut VSTreeMotion(VSIn In)\n"
"{\n"
"    return MotionBoth(Swayed(In.Pos, In.WindA, In.WindB, GScreen.w), Swayed(In.Pos, In.WindA, In.WindB, GLight.x),\n"
"                      float2(0.0f, 0.0f));\n"
"}\n"
"\n"
"// A leaf: one instance - its foot, its size, its twig's bend, its blade's way and its own way along, its picture, hue,\n"
"// phase and fold, how open the plant is round it - and the corner of the blade's frame this vertex is (TreeGen.h's\n"
"// LeafCorner).\n"
"struct LeafIn { float3 Foot : POSITION; float Size : TEXCOORD0; float4 Face : NORMAL; float4 Along : TANGENT;\n"
"                float4 Pack : COLOR; float4 Open : TEXCOORD1; float4 WindA : TEXCOORD2; float4 WindB : TEXCOORD3;\n"
"                uint Corner : SV_VertexID; };\n"
"struct LeafCornerAt { float3 W; float3 N; float2 Uv; float Off; };\n"
"\n"
"// A leaf's corner at a time. Its frame turned with the plant; its size by the plant's stretch, and larger on a far\n"
"// plant drawing a share. Its foot swayed with its twig; the blade at rest - each half rising from the midrib, the tip\n"
"// hanging - and its own flutter: it lifts and falls about its stalk and twists about its midrib, each leaf in its own\n"
"// time, as much as the wind blows outdoors and more as a gust goes by - none with no wind. The normal is the half's\n"
"// at rest.\n"
"LeafCornerAt LeafAt(LeafIn In, float Tm)\n"
"{\n"
"    const float  C     = cos(GPlace.w), S = sin(GPlace.w);\n"
"    const float3 F0    = normalize(In.Face.xyz), A0 = normalize(In.Along.xyz);\n"
"    const float3 Face  = float3(C * F0.x - S * F0.y, S * F0.x + C * F0.y, F0.z);\n"
"    const float3 Along = float3(C * A0.x - S * A0.y, S * A0.x + C * A0.y, A0.z);\n"
"    const float3 Side  = cross(Face, Along);\n"
"    const float  Size  = In.Size * 0.5f * (GSize.x + GSize.y) * GSize.w;\n"
"    const float  Width = Size * ((GLight.z > 0.0f) ? GLight.z : 0.5f);\n"
"    const uint   Pic   = (uint)(In.Pack.x * 255.0f + 0.5f);\n"
"    const float  Droop = (float)(Pic >> 2) / 63.0f * 0.4f;\n"
"    const float  Fold  = In.Pack.w * 0.5f;\n"
"    const int    Cc    = (int)(In.Corner % 3u), Row = (int)(In.Corner / 3u);\n"
"    const float  Uu    = (float)(Cc - 1) * 0.5f, T = (float)Row / 3.0f, Hand = (float)(Cc - 1);\n"
"    const float3 Ft    = Swayed(In.Foot, In.WindA, In.WindB, Tm);\n"
"    const float  Ph    = 6.2831853f * In.Pack.z;\n"
"    const float  Gust  = length(WindAt(GPlace.xy, Tm)) * GWindWave.z;\n"
"    const float  Blow  = GLight.y * GWindWave.z;\n"
"    const float  Flap  = (0.06f * Blow + 0.6f * Gust) * sin(Tm * (5.0f + 3.0f * In.Pack.z) + Ph);\n"
"    const float  Twist = (0.05f * Blow + 0.5f * Gust) * sin(Tm * (7.0f + 2.0f * In.Pack.z) + 1.7f * Ph);\n"
"    float3 P = Along * (T * Size) + Side * (Uu * Width) + Face * (2.0f * abs(Uu) * Fold * Width - Droop * T * T * Size);\n"
"    P += Face * (Flap * T * Size + Twist * Uu * Width);\n"
"    LeafCornerAt Out;\n"
"    Out.W  = Ft + P;\n"
"    Out.N  = normalize(cross(Along * Size - Face * (2.0f * Droop * T * Size), Side * Width + Face * (2.0f * Hand * Fold * Width)));\n"
"    Out.Uv = float2(((float)(Pic & 3u) + Uu + 0.5f) * 0.25f, 1.0f - T);\n"
"    // How far the blade lies off the flat through its four outer corners (RdxTree::LeafFlat), along its face at most:\n"
"    // its halves' fold, from the edges down to the midrib, and the most its hang's curve leaves the straight.\n"
"    Out.Off = Fold * Width + 0.25f * Droop * Size;\n"
"    return Out;\n"
"}\n"
"\n"
"VSOut VSLeaf(LeafIn In)\n"
"{\n"
"    const LeafCornerAt L = LeafAt(In, GScreen.w);\n"
"    // The light on the half the eye sees, a quarter of what reaches its back shining through, each way's by how open\n"
"    // the crown is that way round the leaf; a few leaves yellower.\n"
"    const float3 Eye  = -(GView[0].xyz * GView[0].w + GView[1].xyz * GView[1].w + GView[2].xyz * GView[2].w);\n"
"    const float3 Seen = (dot(L.N, Eye - L.W) >= 0.0f) ? L.N : -L.N;\n"
"    const float3 Lit  = 0.8f * CubeLight(Seen, In.Open) + 0.25f * CubeLight(-Seen, In.Open);\n"
"    const float3 Tint = lerp(float3(1.0f, 1.0f, 1.0f), float3(1.25f, 1.08f, 0.55f), In.Pack.y);\n"
"    VSOut O;\n"
"    O.Uv     = L.Uv;\n"
"    O.Lv     = float2(0.5f, 0.5f);\n"
"    O.Colour = float4(Lit * Tint, 1.0f);\n"
"    O.Pom    = 0.0f;\n"
"    OnScreen(L.W, O);\n"
"    return O;\n"
"}\n"
"\n"
"// The motion vectors' pass: the leaf now and the frame before, its picture's place for the cut-out.\n"
"MotionOut VSLeafMotion(LeafIn In)\n"
"{\n"
"    const LeafCornerAt Now = LeafAt(In, GScreen.w), Before = LeafAt(In, GLight.x);\n"
"    // Laid flat in this pass (RdxTree::LeafFlat: its four outer corners, a third of the corners to lay twice): its depth\n"
"    // taken as much nearer as the blade lies off that flat (Off), so the test still finds the leaf the scene's depth\n"
"    // holds; its vector is the blade's, the wind moving the two alike.\n"
"    MotionOut O = MotionBoth(Now.W, Before.W, Now.Uv);\n"
"    O.Pos.z *= O.Pos.w / max(O.Pos.w - Now.Off, 0.5f * O.Pos.w);\n"
"    return O;\n"
"}\n";
