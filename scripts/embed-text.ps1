# Puts text files into one C++ header, each as a byte array ending in a zero - for the shaders the renderer compiles at
# run time from files of their own (ShadowFactor.hlsl and what it includes), so the DLL carries their text and nothing
# sits next to it. Run by the build (RevisionDX12.vcxproj, the CustomBuild step of ShadowFactor.hlsl), not by hand.
#
#   -Out   the header to write
#   -Pairs name=path;name=path - each file's array name and the file, separated by semicolons (a -File call from the
#          build hands a list over as one string)
#
# Plain ASCII only: a shader's text stays English, and a byte above 127 would be a character the run-time compiler reads
# in some code page of its own. The build stops on one, naming the file and the line.
param(
    [Parameter(Mandatory = $true)][string]$Out,
    [Parameter(Mandatory = $true)][string]$Pairs
)
$ErrorActionPreference = 'Stop'

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by scripts/embed-text.ps1 at build time - do not edit, and do not add to the sources.')
[void]$sb.AppendLine('#pragma once')
foreach ($pair in ($Pairs -split ';' | Where-Object { $_.Trim() })) {
    $pair = $pair.Trim()
    $eq = $pair.IndexOf('=')
    if ($eq -le 0) { throw "embed-text: '$pair' is not name=path" }
    $name = $pair.Substring(0, $eq)
    $path = $pair.Substring($eq + 1)
    $bytes = [System.IO.File]::ReadAllBytes($path)
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        if ($bytes[$i] -gt 127) {
            $line = 1
            for ($k = 0; $k -lt $i; $k++) { if ($bytes[$k] -eq 10) { $line++ } }
            throw "embed-text: $path line $line has a byte above 127 - the file must be plain ASCII"
        }
    }
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("// $([System.IO.Path]::GetFileName($path)), $($bytes.Length) bytes")
    [void]$sb.AppendLine("static const char $name[] = {")
    for ($i = 0; $i -lt $bytes.Length; $i += 32) {
        $n = [Math]::Min(32, $bytes.Length - $i)
        $row = New-Object System.Text.StringBuilder
        for ($k = 0; $k -lt $n; $k++) { [void]$row.Append($bytes[$i + $k]).Append(',') }
        [void]$sb.AppendLine('    ' + $row.ToString())
    }
    [void]$sb.AppendLine('    0')
    [void]$sb.AppendLine('};')
}
$dir = [System.IO.Path]::GetDirectoryName($Out)
if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Force $dir | Out-Null }
[System.IO.File]::WriteAllText($Out, $sb.ToString(), [System.Text.Encoding]::ASCII)
